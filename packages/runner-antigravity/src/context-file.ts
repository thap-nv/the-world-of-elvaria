// GEMINI.md at the root of the plot (implementation-plan §3.8, spike P1-12a §1 #15): the system part of the
// prompt, then `@[label](./path)` lines that agy embeds verbatim, so CLAUDE.md and the territory's rules reach
// the model without a copy that could drift. agy caps an embedded file at 24 000 bytes (cli-facts §2.3).
import { readdir } from 'node:fs/promises';
import path from 'node:path';

export const CONTEXT_HEADER = '<!-- generated by Elvaria; not committed -->';
const LAW_FILE = 'CLAUDE.md';
/** CLAUDE.md has its own line; a README is the territory's front page, not its law (§3.8). */
const NOT_RULES: ReadonlySet<string> = new Set(['claude.md', 'readme.md']);
/** An embed is a markdown link: a space or a bracket in the path would break it. */
const LINKABLE = /^[^\s()[\]]+$/;

const wildcard = (pattern: string): RegExp =>
  new RegExp(
    `^${pattern
      .replace(/[.+^${}()|\\]/g, '\\$&')
      .replaceAll('*', '.*')
      .replaceAll('?', '.')}$`,
    'i',
  );

async function namesIn(dir: string): Promise<string[]> {
  try {
    return (await readdir(dir, { withFileTypes: true }))
      .filter((entry) => entry.isFile())
      .map(({ name }) => name);
  } catch {
    return [];
  }
}

/**
 * The files of `territory.context_files` present in the plot, relative with `/`. A wildcard may stand in the
 * last segment only (`.claude/rules/*.md`); that is what territories use, and it needs no glob library.
 */
export async function contextFilesIn(plot: string, patterns: readonly string[]): Promise<string[]> {
  const found = new Set<string>();
  for (const pattern of patterns) {
    const parts = pattern.replaceAll('\\', '/').replace(/^\.\//, '').split('/');
    const last = parts.pop() ?? '';
    if (parts.some((part) => /[*?]/.test(part))) continue;
    const names = await namesIn(path.join(plot, ...parts));
    const matches = wildcard(last);
    for (const name of names) if (matches.test(name)) found.add([...parts, name].join('/'));
  }
  return [...found].sort();
}

/** The text of GEMINI.md; `files` from contextFilesIn. Quest and scripture stay in the prompt (§3.8). */
export function contextFileText(system: string, files: readonly string[]): string {
  const law = files.find((file) => file.toLowerCase() === LAW_FILE.toLowerCase());
  const rules = files.filter(
    (file) => !NOT_RULES.has(path.posix.basename(file).toLowerCase()) && LINKABLE.test(file),
  );
  const embeds = [
    ...(law === undefined ? [] : [`@[Territory law](./${law})`]),
    ...rules.map((file) => `@[rule](./${file})`),
  ];
  const territory = embeds.length === 0 ? [] : ['# Territory law and rules', '', ...embeds, ''];
  return [CONTEXT_HEADER, '', system.trim(), '', ...territory].join('\n');
}

export const isElvariaContext = (text: string): boolean => text.startsWith(CONTEXT_HEADER);
