// How the Elvaria hook reaches agy (implementation-plan §3.7, spike P1-12a §4, ADR 0015): agy runs a hook as
// one string through `cmd /c` (macOS: `sh -c`) and turns `"` into `\"`, so no quoted path survives. hooks.json
// names a relative shim, `node elvaria-hook.mjs <Event>`, run with cwd `.agents/`; the shim holds the paths.
import { statSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import type { Launch } from './process/child.ts';

export const AGENTS_DIR = '.agents';
export const HOOKS_FILE = 'hooks.json';
export const SHIM_FILE = 'elvaria-hook.mjs';
/** The top-level key of hooks.json: agy names each hook by it, and `/hooks` lists it. */
export const HOOK_NAME = 'elvaria';
/** SessionStart starts the handover gate, PreToolUse is the mandatory fence, Stop asks for the letter. */
export const HOOK_EVENTS = ['SessionStart', 'PreToolUse', 'PostToolUse', 'Stop'] as const;
const TOOL_EVENTS: ReadonlySet<string> = new Set(['PreToolUse', 'PostToolUse']);
/** Seconds (agy's unit). The hook takes < 100 ms; a cold Windows machine can take a few seconds. */
const HOOK_TIMEOUT_S = 10;
/** A Node flag in hooks.json reaches the shell unquoted, so it may hold no space and no quote. */
const SHELL_SAFE = /^[\w.=:,+@/-]+$/;

export interface HookPlan {
  /** The hook script the shim imports (`HOOK_SCRIPT` of @elvaria/hooks). */
  readonly script: string;
  /** Node flags before the script: `--conditions=elvaria-dist`. */
  readonly node_flags: readonly string[];
  /** Folder of the Node that runs Elvaria, put first on agy's PATH so the hook's bare `node` is that one. */
  readonly node_dir: string | undefined;
}

/**
 * Reads `hookCommand()` of @elvaria/hooks (`{command: <node>, args: [...flags, <script>, --policy?]}`), which
 * apps/cli hands to every adapter: the script is the first argument that is not a flag.
 */
export function hookPlanOf(hook: Launch): HookPlan {
  const index = hook.args.findIndex((arg) => !arg.startsWith('-'));
  const script = hook.args[index];
  if (script === undefined) throw new Error('the hook command names no script');
  const flags = hook.args.slice(0, index);
  const unsafe = flags.find((flag) => !SHELL_SAFE.test(flag));
  if (unsafe !== undefined) throw new Error(`hook flag ${unsafe} cannot reach agy's shell unquoted`);
  const nodeDir = path.isAbsolute(hook.command) ? path.dirname(hook.command) : undefined;
  return { script, node_flags: flags, node_dir: nodeDir };
}

/** `.agents/hooks.json`: one hook named `elvaria`, the event in argv because agy's payload has none. */
export function hooksJson(plan: HookPlan): string {
  const handler = (event: string) => ({
    type: 'command',
    command: ['node', ...plan.node_flags, SHIM_FILE, event].join(' '),
    timeout: HOOK_TIMEOUT_S,
  });
  const events: Record<string, unknown[]> = {};
  for (const event of HOOK_EVENTS)
    events[event] = TOOL_EVENTS.has(event) ? [{ matcher: '*', hooks: [handler(event)] }] : [handler(event)];
  return `${JSON.stringify({ [HOOK_NAME]: events }, null, 2)}\n`;
}

/** `.agents/elvaria-hook.mjs`: adds the run's policy to argv and runs the real hook. */
export function shimSource(plan: HookPlan, policyFile: string): string {
  return [
    '// Generated by Elvaria for one run; not committed (.git/info/exclude, ADR 0012). agy runs hooks through',
    '// cmd /c, which mangles quotes, so the paths live here and not in hooks.json (ADR 0015).',
    `process.argv.push('--policy', ${JSON.stringify(policyFile)});`,
    `await import(${JSON.stringify(pathToFileURL(plan.script).href)});`,
    '',
  ].join('\n');
}

/** A hooks.json Elvaria wrote: only the `elvaria` hook. Any other is the territory's and is not overwritten. */
export function isElvariaHooks(text: string): boolean {
  try {
    const value: unknown = JSON.parse(text);
    return typeof value === 'object' && value !== null && Object.keys(value).join() === HOOK_NAME;
  } catch {
    return false;
  }
}

interface ListedHook {
  readonly name?: unknown;
  readonly enabled?: unknown;
  readonly source?: unknown;
  readonly actions?: readonly { readonly event?: unknown }[];
}

/**
 * Whether `source` is the hooks.json at `file`: the same file on disk, whatever the spelling (a Windows temp
 * folder can read `RUNNER~1` one way and `runneradmin` the other; macOS `/var` is `/private/var`).
 */
export function sameFile(source: string, file: string): boolean {
  try {
    const [a, b] = [statSync(source, { bigint: true }), statSync(file, { bigint: true })];
    return a.dev === b.dev && a.ino === b.ino;
  } catch {
    return false;
  }
}

/**
 * What is wrong with the hooks agy loads for the plot (`agy -p /hooks --output-format json`, 0 tokens): ours
 * must be there with its four events, and nothing else, since another PreToolUse hook answering `auto_approve`
 * would pass even `permissions.deny` (spike §4).
 */
export function hooksProblem(stdout: string, hooksFile: string): string | undefined {
  let hooks: readonly ListedHook[];
  try {
    const value = JSON.parse(stdout) as { command?: { data?: { hooks?: unknown } } };
    const listed = value.command?.data?.hooks;
    if (!Array.isArray(listed)) return 'agy -p /hooks gave no hook list';
    hooks = listed as ListedHook[];
  } catch {
    return 'agy -p /hooks did not answer JSON';
  }
  const ours = hooks.find(
    (hook) => hook.name === HOOK_NAME && typeof hook.source === 'string' && sameFile(hook.source, hooksFile),
  );
  if (ours === undefined) return `agy did not load ${hooksFile}`;
  if (ours.enabled !== true) return `agy loaded ${hooksFile} disabled`;
  const events = new Set((ours.actions ?? []).map((action) => action.event));
  const missing = HOOK_EVENTS.filter((event) => !events.has(event));
  if (missing.length > 0) return `agy did not load the hooks ${missing.join(', ')} of ${hooksFile}`;
  const others = hooks
    .filter((hook) => hook !== ours)
    .map((hook) => `${String(hook.name)} (${String(hook.source)})`);
  return others.length === 0
    ? undefined
    : `agy also runs hooks Elvaria does not control: ${others.join('; ')}`;
}
