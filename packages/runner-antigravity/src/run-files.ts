// The files one agy session runs on (implementation-plan §2.2, §3.7): settings, policy and schema in the run
// folder; hooks.json, its shim and GEMINI.md in the plot, excluded from git when the territory was attached
// (ADR 0012). Never in the user's ~/.gemini: `--settings` loads rules for this run only and saves nothing.
// agy loads hooks only from `.agents/` in the workspace or from ~/.gemini/config/ (its bundled docs, 1.5.3), so the
// plot's files live as long as the session and go when it ends (P1-23): the checks the Steward runs next, and any
// other tribe's session, see the plot as the territory has it.
import { mkdir, readFile, rm, rmdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { writePolicyFile } from '@elvaria/runner-core';
import type { RunContext, SpawnRequest } from '@elvaria/runner-core';

import { contextFileText, contextFilesIn, isElvariaContext } from './context-file.ts';
import { AGENTS_DIR, HOOKS_FILE, SHIM_FILE, hooksJson, isElvariaHooks, shimSource } from './hook-files.ts';
import { CONTEXT_FILE, agySettingsOf } from './settings.ts';
import type { HookPlan } from './hook-files.ts';

export interface RunFiles {
  readonly settings: string;
  /**
   * policy.json v1 of runner-core's `writePolicyFile`: the laws, the context, the secret names and the class's
   * tools the hook reads (`--policy`); agy has no `--tools`, so the hook refuses a tool the class lacks (P1-10).
   */
  readonly policy: string;
  readonly hooks: string;
  /** `--log-file`: agy writes the account's e-mail there, so it is private and goes nowhere else (spike §8). */
  readonly log: string;
  readonly schema?: string;
}

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;
const isElvariaShim = (text: string): boolean => text.startsWith('// Generated by Elvaria');

async function existing(file: string): Promise<string | undefined> {
  try {
    return await readFile(file, 'utf8');
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return undefined;
    throw error;
  }
}

/**
 * Writes `text` unless the plot holds the territory's own file there: Elvaria never edits a territory's file,
 * and without its hook this tribe cannot run (spike §10: a territory with its own .agents/hooks.json).
 */
async function writeGenerated(file: string, text: string, ours: (old: string) => boolean): Promise<void> {
  const old = await existing(file);
  if (old !== undefined && !ours(old)) {
    throw new Error(
      `${file} belongs to the territory: the Antigravity tribe cannot run here without editing it (ADR 0018)`,
    );
  }
  await writeFile(file, text, 'utf8');
}

export async function writeRunFiles(req: SpawnRequest, ctx: RunContext, plan: HookPlan): Promise<RunFiles> {
  const agents = path.join(req.cwd, AGENTS_DIR);
  await Promise.all([mkdir(req.run_dir, { recursive: true }), mkdir(agents, { recursive: true })]);
  const files: RunFiles = {
    settings: path.join(req.run_dir, 'settings.json'),
    policy: await writePolicyFile(req.run_dir, ctx, req.permissions),
    hooks: path.join(agents, HOOKS_FILE),
    log: path.join(req.run_dir, 'agy.log'),
    ...(req.structured === undefined ? {} : { schema: path.join(req.run_dir, 'schema.json') }),
  };
  const patterns = ['CLAUDE.md', ...(req.territory?.context_files ?? [])];
  const context = contextFileText(req.prompt.system, await contextFilesIn(req.cwd, patterns));
  await Promise.all([
    writeFile(files.settings, json(agySettingsOf(req.permissions, req.handover)), 'utf8'),
    files.schema === undefined ? undefined : writeFile(files.schema, json(req.structured), 'utf8'),
    writeGenerated(files.hooks, hooksJson(plan), isElvariaHooks),
    writeGenerated(path.join(agents, SHIM_FILE), shimSource(plan, files.policy), isElvariaShim),
    writeGenerated(path.join(req.cwd, CONTEXT_FILE), context, isElvariaContext),
  ]);
  return files;
}

/** A Windows file can stay busy a moment after the tree that held it died; `rm` retries only when recursive. */
const RM_RETRIES = { force: true, recursive: true, maxRetries: 5, retryDelay: 100 } as const;

async function removeGenerated(file: string, ours: (text: string) => boolean): Promise<void> {
  const text = await existing(file);
  if (text !== undefined && ours(text)) await rm(file, RM_RETRIES);
}

/** `.agents/` goes too when nothing of the territory's is left in it. */
async function removeEmptyDir(dir: string): Promise<void> {
  try {
    await rmdir(dir);
  } catch (error) {
    const code = error instanceof Error && 'code' in error ? error.code : undefined;
    if (code !== 'ENOENT' && code !== 'ENOTEMPTY' && code !== 'EEXIST') throw error;
  }
}

/**
 * Takes Elvaria's files out of the plot once the session is over, or never started (P1-23): a formatter or linter
 * the territory runs as a check would read them (phase-1 report §5.3). A file that is not Elvaria's stays.
 */
export async function removeRunFiles(plot: string): Promise<void> {
  const agents = path.join(plot, AGENTS_DIR);
  await Promise.all([
    removeGenerated(path.join(agents, HOOKS_FILE), isElvariaHooks),
    removeGenerated(path.join(agents, SHIM_FILE), isElvariaShim),
    removeGenerated(path.join(plot, CONTEXT_FILE), isElvariaContext),
  ]);
  await removeEmptyDir(agents);
}
