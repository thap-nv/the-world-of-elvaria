// PlotManager.restore (P1-44, P1-37 (f)): after a judge outside a scratch plot, the plot goes back to its commit.
// What the judge's commands changed there (a generator, a formatter) is dropped, tracked or not; what git ignores
// and the runner files the plot excludes stay. A real git repo in a temp folder with a space in its name.
import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { fromPortable, pathExists } from '@elvaria/store';
import type { Plot } from '@elvaria/domain';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { RM_TEMP } from '../__fixtures__/temp.ts';
import { TEST_HOST, commitFile, git, gitRepo, questId, territoryAt } from '../__fixtures__/git-repo.ts';
import { createPlotManager } from './plot-manager.ts';

let root = '';
beforeAll(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'elvaria plot restore '));
});
afterAll(() => rm(root, RM_TEMP));

const plots = () => createPlotManager({ kingdom: path.join(root, 'kingdom'), host: TEST_HOST });

async function preparedPlot(name: string, suffix: string) {
  // The repo ignores node_modules, as a real territory does.
  const repo = await gitRepo(path.join(root, name));
  await commitFile(repo, 'apps/api/openapi.json', '{"paths": {"/periods": {}}}\n');
  await commitFile(repo, 'apps/api/types.ts', 'export type Period = string;\n');
  const prepared = await plots().prepare({ id: questId(suffix) }, territoryAt(repo));
  if (!prepared.ok) throw new Error(`prepare failed: ${prepared.error.detail}`);
  return { plot: prepared.value.plot, worktree: fromPortable(prepared.value.plot.path!) };
}

describe('restore', () => {
  it('drops what changed since the commit, keeps what git ignores, and names the paths it dropped', async () => {
    const { plot, worktree } = await preparedPlot('generated repo', 'e1f2a3');
    const head = git(worktree, 'rev-parse', 'HEAD');
    // A generator rewrote the contract and left output around; a formatter renamed a file and staged it.
    await writeFile(path.join(worktree, 'apps', 'api', 'openapi.json'), '{"paths": {}}\n');
    await mkdir(path.join(worktree, 'coverage'));
    await writeFile(path.join(worktree, 'coverage', 'summary.json'), '{}\n');
    await writeFile(path.join(worktree, 'stray.txt'), 'left by a command\n');
    await rename(
      path.join(worktree, 'apps', 'api', 'types.ts'),
      path.join(worktree, 'apps', 'api', 'api-types.ts'),
    );
    git(worktree, 'add', '--all', 'apps/api');
    await mkdir(path.join(worktree, 'node_modules', 'pkg'), { recursive: true });
    await writeFile(path.join(worktree, 'node_modules', 'pkg', 'index.js'), 'module.exports = 1;\n');
    // A file a runner generates at the plot's root is excluded (ADR 0012): never the judge's dirt.
    await writeFile(path.join(worktree, 'GEMINI.md'), '<!-- generated by Elvaria; not committed -->\n');

    const dropped = await plots().restore(plot);
    expect([...dropped].sort()).toEqual([
      'apps/api/api-types.ts',
      'apps/api/openapi.json',
      'coverage/',
      'stray.txt',
    ]);
    expect(await plots().status(plot)).toMatchObject({ dirty: false });
    expect(git(worktree, 'rev-parse', 'HEAD')).toBe(head);
    expect(await readFile(path.join(worktree, 'apps', 'api', 'openapi.json'), 'utf8')).toBe(
      '{"paths": {"/periods": {}}}\n',
    );
    expect(await pathExists(path.join(worktree, 'apps', 'api', 'types.ts'))).toBe(true);
    expect(await pathExists(path.join(worktree, 'coverage'))).toBe(false);
    expect(await pathExists(path.join(worktree, 'node_modules', 'pkg', 'index.js'))).toBe(true);
    expect(await pathExists(path.join(worktree, 'GEMINI.md'))).toBe(true);
  });

  it('leaves a clean plot alone, and has nothing to do for a plot without git', async () => {
    const { plot } = await preparedPlot('clean repo', 'b2c3d4');
    expect(await plots().restore(plot)).toEqual([]);
    const folder: Plot = { type: 'folder', path: 'quests/q_20261107_c3d4e5/work' };
    expect(await plots().restore(folder)).toEqual([]);
    expect(await plots().restore({ type: 'none' })).toEqual([]);
  });
});
