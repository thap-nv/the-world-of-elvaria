import { chmod, mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { fromPortable, pathExists } from '@elvaria/store';
import type { Plot } from '@elvaria/domain';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { RM_TEMP } from '../__fixtures__/temp.ts';
import { TEST_HOST, commitFile, git, gitRepo, questId, territoryAt } from '../__fixtures__/git-repo.ts';
import { plotCommitMessage } from './commit-message.ts';
import { createPlotManager } from './plot-manager.ts';
import type { ForgetWorktree } from './worktree-ops.ts';

let root = '';
beforeAll(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'elvaria plot ops '));
});
afterAll(() => rm(root, RM_TEMP));

const forgotten: string[] = [];
const remember: ForgetWorktree = (worktree) => {
  forgotten.push(worktree);
  return Promise.resolve();
};
const plots = () =>
  createPlotManager({ kingdom: path.join(root, 'kingdom'), host: TEST_HOST, forget: [remember] });

/** A prepared plot on a fresh repo named `name`; returns the repo, the plot and its folder. */
async function preparedPlot(name: string, suffix: string) {
  const repo = await gitRepo(path.join(root, name));
  await commitFile(repo, 'src/app.ts', 'export const app = 1;\n');
  const prepared = await plots().prepare({ id: questId(suffix) }, territoryAt(repo));
  if (!prepared.ok) throw new Error(`prepare failed: ${prepared.error.detail}`);
  return { repo, plot: prepared.value.plot, worktree: fromPortable(prepared.value.plot.path!) };
}

describe('status and touched', () => {
  it('count from the fork point: committed, uncommitted, deleted and new files', async () => {
    const { repo, plot, worktree } = await preparedPlot('status repo', 'a2b3c4');
    expect(await plots().status(plot)).toEqual({ dirty: false, ahead: 0, branch: 'quest/q_20261107_a2b3c4' });
    expect(await plots().touched(plot)).toEqual([]);

    await commitFile(worktree, 'src/feature.ts', 'export const feature = 1;\n');
    await rm(path.join(worktree, 'README.md'));
    await writeFile(path.join(worktree, 'src', 'app.ts'), 'export const app = 2;\n');
    await mkdir(path.join(worktree, 'docs'));
    await writeFile(path.join(worktree, 'docs', 'new.md'), '# new\n');
    // Files a runner generates at the plot's root are excluded, so they are neither dirt nor work.
    await writeFile(path.join(worktree, 'GEMINI.md'), '<!-- generated by Elvaria; not committed -->\n');
    // main moving on does not change what the quest touched.
    await commitFile(repo, 'later.txt', 'later\n');

    expect(await plots().status(plot)).toEqual({ dirty: true, ahead: 1, branch: 'quest/q_20261107_a2b3c4' });
    expect(await plots().touched(plot)).toEqual(['README.md', 'docs/new.md', 'src/app.ts', 'src/feature.ts']);
    // The head is the commit, whatever the worktree holds uncommitted (P1-38).
    expect(await plots().head(plot)).toBe(git(worktree, 'rev-parse', 'HEAD'));
  });

  it('say nothing for plots without git, and list a folder plot whole', async () => {
    const kingdom = path.join(root, 'kingdom');
    const folder: Plot = { type: 'folder', path: 'quests/q_20261107_b3c4d5/work' };
    await mkdir(path.join(kingdom, 'quests', 'q_20261107_b3c4d5', 'work', 'notes'), { recursive: true });
    await writeFile(path.join(kingdom, 'quests', 'q_20261107_b3c4d5', 'work', 'notes', 'a.md'), 'a');
    const none: Plot = { type: 'none' };

    expect(await plots().status(folder)).toEqual({ dirty: false, ahead: 0, branch: null });
    expect(await plots().head(folder)).toBeNull();
    expect(await plots().head(none)).toBeNull();
    expect(await plots().touched(folder)).toEqual(['notes/a.md']);
    expect(await plots().touched({ type: 'folder', path: 'quests/q_20261107_c4d5e6/work' })).toEqual([]);
    expect(await plots().touched(none)).toEqual([]);
    expect(await plots().commitAll(folder, 'submit')).toEqual({ status: 'no_git' });
    expect(await plots().release(none)).toEqual({ ok: true, value: { removed: false, forget_failures: [] } });
  });
});

describe('commitAll', () => {
  it('makes exactly one commit of everything when dirty, and none when clean', async () => {
    const { plot, worktree } = await preparedPlot('commit repo', 'd5e6f7');
    await writeFile(path.join(worktree, 'src', 'app.ts'), 'export const app = 3;\n');
    await writeFile(path.join(worktree, 'notes.md'), 'new file\n');
    await writeFile(path.join(worktree, 'GEMINI.md'), 'generated\n');

    const message = plotCommitMessage.submit(questId('d5e6f7'));
    const committed = await plots().commitAll(plot, message);
    const again = await plots().commitAll(plot, message);

    expect(committed).toEqual({ status: 'committed', sha: git(worktree, 'rev-parse', 'HEAD') });
    expect(again).toEqual({ status: 'clean' });
    expect(git(worktree, 'rev-list', '--count', 'main..HEAD')).toBe('1');
    expect(git(worktree, 'log', '-1', '--format=%s')).toBe('chore: submit q_20261107_d5e6f7');
    expect(git(worktree, 'show', '--name-only', '--format=', 'HEAD').split('\n').sort()).toEqual([
      'notes.md',
      'src/app.ts',
    ]);
    expect(await plots().status(plot)).toMatchObject({ dirty: false, ahead: 1 });
  });

  it("reports a commit the territory's own hook refuses, and leaves the changes in place", async () => {
    const { repo, plot, worktree } = await preparedPlot('hooked repo', 'e6f7g8');
    const hook = path.join(repo, '.git', 'hooks', 'pre-commit');
    await writeFile(hook, '#!/bin/sh\necho "lint failed: src/app.ts" >&2\nexit 1\n');
    await chmod(hook, 0o755);
    await writeFile(path.join(worktree, 'src', 'app.ts'), 'export const app = 4;\n');

    const outcome = await plots().commitAll(plot, plotCommitMessage.wip(questId('e6f7g8'), 'time'));

    expect(outcome).toEqual({ status: 'refused', detail: 'lint failed: src/app.ts' });
    expect(await plots().status(plot)).toMatchObject({ dirty: true, ahead: 0 });
  });
});

describe('release', () => {
  it('removes the worktree with its node_modules, keeps the branch, and lets each tribe forget it', async () => {
    const { repo, plot, worktree } = await preparedPlot('release repo', 'f7g8h9');
    await commitFile(worktree, 'src/done.ts', 'export const done = true;\n');
    // node_modules as pnpm lays it out: the package in its store, a junction (Windows) or symlink to it.
    const stored = path.join(worktree, 'node_modules', '.pnpm', 'left-pad', 'node_modules', 'left-pad');
    await mkdir(stored, { recursive: true });
    await writeFile(path.join(stored, 'index.js'), '');
    await symlink(stored, path.join(worktree, 'node_modules', 'left-pad'), 'junction');
    forgotten.length = 0;

    expect(await plots().release(plot)).toEqual({ ok: true, value: { removed: true, forget_failures: [] } });
    // git keeps the junctions' folders on Windows; release takes them too (P1-11).
    expect(await pathExists(worktree)).toBe(false);
    expect(git(repo, 'worktree', 'list', '--porcelain').match(/^worktree /gm)).toHaveLength(1);
    expect(git(repo, 'log', '-1', '--format=%s', 'quest/q_20261107_f7g8h9')).toBe('add src/done.ts');
    expect(forgotten).toEqual([worktree]);
    // Again after a crash between the two steps: nothing to remove, the CLIs forget once more.
    expect(await plots().release(plot)).toEqual({ ok: true, value: { removed: false, forget_failures: [] } });
    expect(forgotten).toEqual([worktree, worktree]);
  });

  it('refuses a dirty worktree, and reports a forget that fails without failing the release', async () => {
    const { plot, worktree } = await preparedPlot('dirty repo', 'g8h9j0');
    await writeFile(path.join(worktree, 'unsaved.md'), 'not committed\n');
    expect(await plots().release(plot)).toMatchObject({ ok: false, error: { reason: 'dirty' } });

    await rm(path.join(worktree, 'unsaved.md'));
    const failing = createPlotManager({
      kingdom: path.join(root, 'kingdom'),
      host: TEST_HOST,
      forget: [() => Promise.reject(new Error('claude purge: exit 1')), remember],
    });
    expect(await failing.release(plot)).toEqual({
      ok: true,
      value: { removed: true, forget_failures: ['claude purge: exit 1'] },
    });
  });

  it('a released quest prepared again gets its branch back, commits and fork point included', async () => {
    const { repo, plot, worktree } = await preparedPlot('revive repo', 'h9j0k1');
    await commitFile(worktree, 'src/part.ts', 'export const part = 1;\n');
    await plots().release(plot);
    await commitFile(repo, 'main-moved.txt', 'later\n');

    const again = await plots().prepare({ id: questId('h9j0k1') }, territoryAt(repo));

    expect(again).toMatchObject({ ok: true, value: { created: true, plot } });
    expect(await plots().status(plot)).toEqual({ dirty: false, ahead: 1, branch: 'quest/q_20261107_h9j0k1' });
    expect(await plots().touched(plot)).toEqual(['src/part.ts']);
  });
});
