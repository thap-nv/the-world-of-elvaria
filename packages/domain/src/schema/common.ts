// Pieces shared by the contracts; patterns are the `$defs` of the v1 schemas (ADR 0003). A `.meta({ id })` here
// becomes a `$defs` entry in every generated contract that uses it.
import { z } from 'zod';

import { NAME_MAX_LENGTH } from '../constants.ts';

export const AbsPathSchema = z
  .string()
  .regex(/^(?:[A-Za-z]:\/|\/)[^\\]*$/)
  .meta({
    id: 'abs_path',
    description:
      "Absolute path with '/' separators (Windows drive or POSIX root); no backslashes in data files.",
  });
export const ModelSlugSchema = z
  .string()
  .regex(/^[a-z0-9][a-z0-9.-]*$/)
  .meta({ id: 'model_slug' });
export const NameSchema = z.string().min(1).max(NAME_MAX_LENGTH);
export const NonEmptyStringSchema = z.string().min(1);
/** ISO 8601 with an offset (`Z` or `+07:00`), as every timestamp in a kingdom file (implementation-plan §2.1). */
export const DateTimeSchema = z.iso.datetime({ offset: true });

export const RANKS = ['F', 'E', 'D', 'C', 'B', 'A', 'S'] as const;
export const RankSchema = z.enum(RANKS).meta({ id: 'rank' });
export type Rank = z.infer<typeof RankSchema>;

/** verdict.fail_kind and character.consecutive_fail.fail_kind: "the same failure in a row" needs one vocabulary. */
export const FAIL_KINDS = [
  'tests_fail',
  'scope_creep',
  'missing_i18n',
  'wrong_facts',
  'incomplete',
  'style',
  'unsafe',
  'other',
] as const;
export const FailKindSchema = z.enum(FAIL_KINDS);
export type FailKind = z.infer<typeof FailKindSchema>;

/** Who a character is on a quest: quest.attempt_log[].role and character.current.role. */
export const ROLES = ['assignee', 'verifier'] as const;
export const RoleSchema = z.enum(ROLES);
export type Role = z.infer<typeof RoleSchema>;

/** kind.deliverable_type and quest.deliverable.type. */
export const DELIVERABLE_TYPES = ['branch', 'file', 'report', 'draft', 'subquests', 'none'] as const;

/** JSON Schema `uniqueItems` for an array of plain values. */
export const allUnique = (items: readonly unknown[]): boolean => new Set(items).size === items.length;
export const UNIQUE_ITEMS = { message: 'items must be unique' } as const;

/** An array whose items must differ: checked by zod, and stated as `uniqueItems` in the contract. */
export const unique = <T extends z.ZodArray<z.ZodType>>(array: T): T =>
  array.refine(allUnique, UNIQUE_ITEMS).meta({ uniqueItems: true });

/** Adds an issue for every repeated `id` in a list; ids are unique in every file, which JSON Schema cannot say. */
export function rejectDuplicateIds(items: readonly { id: string }[], ctx: z.RefinementCtx): void {
  const seen = new Set<string>();
  items.forEach((item, index) => {
    if (seen.has(item.id))
      ctx.addIssue({ code: 'custom', path: [index, 'id'], message: `duplicate id "${item.id}"` });
    seen.add(item.id);
  });
}

/** The root `$comment` of every generated contract starts with this, then says what the file cannot express. */
