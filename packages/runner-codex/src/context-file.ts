// AGENTS.override.md at the root of the plot (spike Codex 2026-11-12 §1.6, P1-12d): Codex reads it in place of
// AGENTS.md, so it carries the system part of the prompt, then the territory's law and rules copied in (AGENTS.md
// and CLAUDE.md, which it hides or never reads, and `territory.context_files`), then what this CLI's tools are.
// Codex has no include syntax, unlike agy's GEMINI.md, so the files are copied, each cut as runner-core cuts them.
import type { ContextFile, ToolPolicy } from '@elvaria/runner-core';

export const CONTEXT_FILE = 'AGENTS.override.md';
export const CONTEXT_HEADER = '<!-- generated by Elvaria; not committed -->';
/** The territory's law files: AGENTS.md is Codex's own, CLAUDE.md the law of the territories Elvaria grew up on. */
export const LAW_FILES = ['AGENTS.md', 'CLAUDE.md'] as const;

/** How a class without a shell reads a tracked file through `git grep` (P1-53's search commands). */
export const READ_LINE = "git grep -h -n -e '^' -- '<path>'";

/**
 * What Codex's tools are, for the class this session runs: the prompt above names Claude Code's (Read, Glob, Grep,
 * Edit, Write), which Codex does not have (spike §1.7). `sandboxWrites`: the session may write, so git's folder is
 * the read-only part of its sandbox (spike §4).
 */
export function codexNote(
  policy: Pick<ToolPolicy, 'tools' | 'search_commands'>,
  sandboxWrites: boolean,
): string {
  const tools = new Set(policy.tools);
  const search = policy.search_commands ?? [];
  const lines = [
    '# Your tools in Codex CLI',
    '',
    'You run in Codex CLI, whose tools differ from the names used above.',
    '',
  ];
  if (tools.has('Bash')) {
    lines.push(
      '- Codex has no Read, Glob or Grep tool: read, list and search files with read-only commands of your shell (Get-Content, Get-ChildItem, Select-String in PowerShell; git grep, git ls-files).',
    );
  } else if (search.length > 0) {
    lines.push(
      `- Codex has no Read, Glob or Grep tool, and your class has no shell: your shell runs only ${search.join(' and ')}, each alone on its line. Read a file git tracks with \`${READ_LINE}\`.`,
    );
  }
  if (tools.has('Edit') || tools.has('Write')) {
    lines.push('- Change files only with the apply_patch tool, never with the shell.');
  }
  if (sandboxWrites) {
    lines.push(
      "- Git's own folder is read-only in your sandbox, so git add and git commit fail: leave your changes uncommitted; the Steward commits them when the session ends.",
    );
  }
  lines.push(
    '- Do not start sub-agents and do not call request_user_input: both are refused; a question for the owner goes in the Question section of the handover letter.',
    `- ${CONTEXT_FILE} at the root of your plot is this file: Elvaria writes it for the session and removes it when the session ends. Never edit, format or commit it, and leave it out of what you report.`,
  );
  return lines.join('\n');
}

/**
 * The file sits at the root of the plot while the session runs, where the territory's `prettier --check .` finds it
 * (P1-12e: Elvaria's own `format:check` went red in a session). Prettier leaves a Markdown range between these two
 * comments as it is, whatever the territory's settings; the header stays outside it, as Prettier writes it.
 */
export const FORMAT_IGNORE_START = '<!-- prettier-ignore-start -->';
export const FORMAT_IGNORE_END = '<!-- prettier-ignore-end -->';

/** An opening code fence (CommonMark): up to three spaces, then three or more backticks or tildes. */
const FENCE = /^ {0,3}(`{3,}|~{3,})/;

/**
 * `text` with its last code fence closed: a law file cut at runner-core's limit can stop inside a fence, which would
 * swallow every section after it, and the end of Prettier's ignored range with them.
 */
export function closeFences(text: string): string {
  let open: string | undefined;
  for (const line of text.split('\n')) {
    const fence = FENCE.exec(line)?.[1];
    if (fence === undefined) continue;
    if (open === undefined) open = fence;
    // A fence is one character repeated: the same character, at least as many, closes it.
    else if (fence.startsWith(open) && line.trim() === fence) open = undefined;
  }
  return open === undefined ? text : `${text}\n${open}`;
}

/** The text of AGENTS.override.md; `files` the territory's law and rules as runner-core's readContextFiles gives them. */
export function contextFileText(system: string, files: readonly ContextFile[], note: string): string {
  const present = files.filter(({ text }) => text.trim() !== '');
  const territory =
    present.length === 0
      ? []
      : [
          '# Territory law and rules',
          '',
          ...present.flatMap(({ path, text }) => [`## ${path}`, '', closeFences(text.trim()), '']),
        ];
  const body = [closeFences(system.trim()), '', ...territory, note];
  return [CONTEXT_HEADER, '', FORMAT_IGNORE_START, ...body, FORMAT_IGNORE_END, ''].join('\n');
}

export const isElvariaContext = (text: string): boolean => text.startsWith(CONTEXT_HEADER);
